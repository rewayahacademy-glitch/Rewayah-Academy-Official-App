--
-- FICHIER SEPARE de la partie a (20261123300000_sec_garde_4_lectures.sql) :
-- il contient les mots TRUNCATE et DELETE (dans REVOKE), que le serveur
-- Supabase fait confirmer une seconde fois. Il se colle donc a la main, sur
-- decision du directeur ; la partie a s'installe sans lui.
--
-- Le defaut : les privileges par defaut de Supabase donnent a anon et
-- authenticated tous les droits sur chaque table de public. La RLS borne les
-- lignes de SELECT, INSERT, UPDATE et DELETE, mais TRUNCATE ne passe pas par
-- la RLS, REFERENCES permet de sonder les cles d'une table par une contrainte
-- etrangere, et TRIGGER n'a aucun usage client. Sur une base rejouee depuis
-- le depot (PostgreSQL 16, main du 11/11), 61 tables donnent deja l'un de ces
-- trois droits a anon ou authenticated ; en production, sans doute toutes.
--
-- Ce que fait ce fichier, et rien d'autre :
--   1. REVOKE TRUNCATE, REFERENCES, TRIGGER FROM anon, authenticated sur
--      TOUTES les tables de public (188, partition audit_logs_default
--      comprise) ;
--   2. REVOKE UPDATE FROM anon, authenticated sur les 152 tables qui n'ont
--      AUCUNE politique UPDATE ni ALL ;
--   3. REVOKE DELETE FROM anon, authenticated sur les 155 tables qui n'ont
--      AUCUNE politique DELETE ni ALL.
-- Les listes sont ECRITES EN DUR (aucune boucle dynamique), tirees de la
-- requete de preflight ci-dessous sur la base rejouee. Sans politique, la RLS
-- rendait deja 0 ligne : le REVOKE ne retire aucun geste, il ferme le droit.
-- Ni ALTER DEFAULT PRIVILEGES, ni service_role, ni SELECT ni INSERT, ni les
-- vues ne sont touches. Un REVOKE d'un droit non donne ne fait rien.
--
-- Verifie avant d'ecrire la liste (base rejouee) :
--   - aucune ecriture directe du client Dart (update, delete, upsert) ne vise
--     une table des listes 2 et 3 ;
--   - les fonctions SECURITY INVOKER qui modifient ces tables sont dans
--     private (sans USAGE pour anon ni authenticated, appelees depuis des RPC
--     DEFINER) ou sont des declencheurs de tables sans politique d'ecriture
--     (groupes, download_asset) : jamais executees au nom d'un client ;
--   - les droits UPDATE par colonne donnes a authenticated (learning_assignment,
--     notifications, student_profiles) sont sur des tables qui ont une
--     politique UPDATE : hors liste.
--
-- PREFLIGHT, a relire EN PRODUCTION par le pilote avant le collage (lecture
-- seule) ; les trois listes doivent etre identiques a celles de ce fichier :
--   SELECT c.relname FROM pg_catalog.pg_class c
