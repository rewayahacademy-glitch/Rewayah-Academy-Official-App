-- POSTFLIGHT : plus aucun TRUNCATE, REFERENCES ni TRIGGER pour anon ou
-- authenticated sur une table listee ; plus d'UPDATE ni d'effacement sur les
-- listes 2 et 3.
DO $postflight$
DECLARE
  v_n integer;
BEGIN
  SELECT count(*) INTO v_n
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace,
         LATERAL pg_catalog.aclexplode(coalesce(c.relacl, pg_catalog.acldefault('r', c.relowner))) a
   WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
     AND a.grantee IN ('anon'::regrole, 'authenticated'::regrole)
     AND a.privilege_type IN ('TRUNCATE', 'REFERENCES', 'TRIGGER');
  IF v_n > 0 THEN
    RAISE EXCEPTION 'SEC-GARDE-4 b : % droits TRUNCATE, REFERENCES ou TRIGGER restent', v_n;
  END IF;
  SELECT count(*) INTO v_n
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace,
         LATERAL pg_catalog.aclexplode(coalesce(c.relacl, pg_catalog.acldefault('r', c.relowner))) a
   WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
     AND a.grantee IN ('anon'::regrole, 'authenticated'::regrole)
     AND ((a.privilege_type = 'UPDATE'
           AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_policy p
                            WHERE p.polrelid = c.oid AND p.polcmd IN ('w', '*')))
       OR (a.privilege_type = 'DELETE'
           AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_policy p
                            WHERE p.polrelid = c.oid AND p.polcmd IN ('d', '*'))));
  IF v_n > 0 THEN
    RAISE EXCEPTION 'SEC-GARDE-4 b : % droits d''ecriture sans politique restent', v_n;
  END IF;
END
$postflight$;
